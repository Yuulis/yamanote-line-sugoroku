import type { Map as MapLibreMap } from "maplibre-gl";
import type { CameraPadding } from "./camera";
import type { ClearReplayBounds } from "./clearRouteCamera";
import { readRouteImageProbeOutput } from "./routeImageExportProbe";
import type { RouteImageInput, RouteImageState } from "./routeImage";

/**
 * Observation point for the Playwright suite (tests/e2e). The map is drawn on
 * a canvas, so the marker position and the completed-segment filter cannot be
 * read from the DOM; the E2E build publishes the live map on
 * `window.__sugorokuE2E.map` instead.
 *
 * Absent from production: only `vite build --mode e2e` (the Playwright
 * webServer) sets `import.meta.env.MODE` to "e2e". Vite replaces MODE with a
 * string literal at build time, so in every other build the condition below
 * is the constant `false` and the minifier drops the body, key included.
 */
const E2E_HOOK_ENABLED = import.meta.env.MODE === "e2e";

interface SugorokuE2EHook {
  readonly [key: string]: unknown;
  readonly map?: MapLibreMap | null;
  readonly corridorOffsetMetrics?: {
    readonly state: "pending" | "applied" | "failed" | "unsupported";
    readonly canonicalCount: number;
    readonly derivedCount: number | null;
    readonly postMessageMs: number | null;
    readonly replyHandlingMs: number | null;
    readonly workerDerivationMs: number | null;
    readonly requestStartedAt: number | null;
    readonly loadToAppliedMs: number | null;
    readonly renderLatencyMs: number | null;
  };
  readonly clearFitPadding?: CameraPadding | null;
  readonly clearCameraTarget?: { readonly bounds: ClearReplayBounds; readonly recordIndex: number | null } | null;
  readonly clearFitCount?: number;
  readonly routeImageInput?: RouteImageInput | null;
  readonly routeImageState?: RouteImageState;
  readonly runRouteImageExportProbe?: () => Promise<{
    size: number;
    routeColors: readonly string[];
    routeBounds: RouteImageInput["route"]["bounds"];
  }>;
  readonly routeImageProbeBlob?: Blob;
}

function updateE2EHook(values: Partial<SugorokuE2EHook>): void {
  if (!E2E_HOOK_ENABLED) return;
  const windowWithHook = window as unknown as { __sugorokuE2E?: SugorokuE2EHook };
  windowWithHook.__sugorokuE2E = { ...windowWithHook.__sugorokuE2E, ...values };
}

if (E2E_HOOK_ENABLED) {
  updateE2EHook({
    clearFitCount: 0,
    runRouteImageExportProbe: async () => {
      const hook = (window as unknown as { __sugorokuE2E?: SugorokuE2EHook }).__sugorokuE2E;
      const output = readRouteImageProbeOutput(
        hook?.routeImageInput ?? null,
        hook?.routeImageState ?? { kind: "unavailable" },
      );
      updateE2EHook({ routeImageProbeBlob: output.blob });
      return { size: output.blob.size, routeColors: [...output.colors], routeBounds: output.bounds };
    },
  });
}

/** Publish the map once its layers exist; pass null when it is removed. */
export function exposeMapForE2E(map: MapLibreMap | null): void {
  updateE2EHook({ map, clearFitPadding: null });
}

/** Expose the cold shared-track derivation measured by the perf harness. */
export function exposeCorridorOffsetMetricsForE2E(metrics: SugorokuE2EHook["corridorOffsetMetrics"]): void {
  updateE2EHook({ corridorOffsetMetrics: metrics });
}

/** Expose the actual padding passed to the live map's latest clear-route fit. */
export function exposeClearFitPaddingForE2E(padding: CameraPadding | null): void {
  updateE2EHook({ clearFitPadding: padding === null ? null : { ...padding } });
}

/** Expose the latest clear replay camera target for the end-to-end framing checks. */
export function exposeClearCameraTargetForE2E(bounds: ClearReplayBounds | null, recordIndex: number | null): void {
  updateE2EHook({ clearCameraTarget: bounds === null ? null : { bounds, recordIndex } });
}

/** Count clear-route fits that were actually applied by the live replay camera. */
export function incrementClearFitCountForE2E(): void {
  if (!E2E_HOOK_ENABLED) return;
  const hook = (window as unknown as { __sugorokuE2E?: SugorokuE2EHook }).__sugorokuE2E;
  updateE2EHook({ clearFitCount: (hook?.clearFitCount ?? 0) + 1 });
}

/** Keep the published clear's exporter input and generated bytes available to the e2e-only image probe. */
export function exposeRouteImageForE2E(input: RouteImageInput | null, state: RouteImageState): void {
  updateE2EHook({ routeImageInput: input, routeImageState: state });
}
